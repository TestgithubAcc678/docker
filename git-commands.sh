# Commit commands
git add .                    # Добовить индексацию
git commit -m "Discription"     # Сделать коммит
git push # Отправить изменения в удаленный репозиторий

git pull # Слить измененияиз удаленно репозитория

# Branches commands
git branch -m old-branch new-branch # Создать новую ветку
git switch # Переключиться на новую ветку

